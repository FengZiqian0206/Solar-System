const assert=require('node:assert/strict');
(async()=>{
  const {createPointInfluence}=await import('./point-influence.js');
  const step=52/49, c=-26+25*step, center={x:c,y:c,z:c};
  const index=(x,y=25,z=25)=>(x*50+y)*50+z;
  const field=createPointInfluence(50,26);
  field.update(center,.05);
  assert.ok(field.values[index(26)]>0 && field.values[index(26)]<.3,'Gradual arrival');
  const firstOffset=field.offsets[index(28)*3];
  assert.ok(firstOffset>0 && firstOffset<step,'Repulsion starts smoothly');
  field.update(center,2);
  assert.ok(field.values[index(26)]>.94);
  assert.equal(field.values[index(27,26)],0,'Reduced radius excludes cells sqrt(5) steps away');
  const pushed=field.offsets[index(28)*3];
  assert.ok(pushed>step*1.5 && pushed<=step*1.8,'Nearby shell clearly pushed outward');
  assert.ok(Math.abs(pushed+field.offsets[index(22)*3])<.00001,'Symmetric outward displacement');
  assert.equal(field.offsets[index(26)*3],0,'Colour core stays on its grid');
  assert.equal(field.offsets[index(31)*3],0,'Distant grid stays intact');
  const before=field.values[index(26)];
  field.update(null,.5);
  assert.ok(field.values[index(26)]>before*.7 && field.values[index(26)]<before,'Slow departure');
  assert.ok(field.offsets[index(28)*3]>pushed*.6 && field.offsets[index(28)*3]<pushed*.7,'Brief lingering before returning');
  field.update(null,2);
  assert.ok(field.values[index(26)]>before*.75 && field.values[index(26)]<before*.77,'Longer trail retains about 76% colour after 2.5 seconds');
  assert.ok(field.offsets[index(28)*3]>pushed*.1 && field.offsets[index(28)*3]<pushed*.15,'Most displacement fades within about three seconds');
  field.update(null,6.5);
  assert.ok(Math.abs(field.values[index(26)]/before-Math.exp(-1))<.00001,'Colour fade time constant is nine seconds');
  field.update(null,70); assert.ok(field.values.every(v=>v===0));
  assert.ok(field.offsets.every(v=>v===0),'Eventually fully back on-grid');
  field.reset();field.update({...center,x:c+step*.45},.1);
  assert.ok(field.values[index(27)]>.1,'Next cells begin colouring before a grid snap');
  field.reset();assert.ok(field.values.every(v=>v===0));assert.ok(field.offsets.every(v=>v===0));
  const lingering=createPointInfluence(50,26);
  lingering.update(center,2);
  const nearPush=lingering.offsets[index(28)*3];
  lingering.update({...center,x:c-step*1.5},.3);
  assert.ok(lingering.offsets[index(28)*3]>nearPush*.8 && lingering.offsets[index(28)*3]<nearPush*.9,'Reduced force inside the field also has a shorter recovery');
  const result=[], displacement=[];
  for(const fps of [30,60,120]){
    const f=createPointInfluence(50,26);
    for(let i=0;i<fps;i++)f.update(center,1/fps);
    for(let i=0;i<fps;i++)f.update(null,1/fps);
    result.push(f.values[index(25)]);
    displacement.push(f.offsets[index(28)*3]);
  }
  assert.ok(Math.max(...result)-Math.min(...result)<.00001,'Frame-rate-independent fade');
  assert.ok(Math.max(...displacement)-Math.min(...displacement)<.00001,'Frame-rate-independent repulsion and return');
  field.update({x:-26,y:-26,z:-26},1);
  assert.ok(field.values.every(v=>Number.isFinite(v)&&v>=0&&v<=.95));
  assert.ok(field.offsets.every(v=>Number.isFinite(v)&&Math.abs(v)<=1.8*step),'Finite bounded offsets at cube corner');
  for(const size of [100,150]){
    const fineStep=52/(size-1),middle=Math.floor(size/2),coordinate=-26+middle*fineStep;
    const fine=createPointInfluence(size,26),fineIndex=x=>(x*size+middle)*size+middle;
    fine.update({x:coordinate,y:coordinate,z:coordinate},2);
    assert.ok(fine.values[fineIndex(middle+1)]>.94,`${size}³ core uses the actual grid spacing`);
    const finePush=fine.offsets[fineIndex(middle+3)*3];
    assert.ok(finePush>fineStep*1.5 && finePush<=fineStep*1.8,`${size}³ repulsion remains measured in grid steps`);
    assert.equal(fine.values[fineIndex(middle+6)],0,`${size}³ distant cells remain unchanged`);
  }
  const custom=createPointInfluence(7,3,.5),customIndex=x=>(x*7+3)*7+3;
  custom.update({x:-1.5,y:-1.5,z:-1.5},2);
  assert.ok(custom.values[customIndex(4)]>.94,'Optional grid spacing matches custom vertex coordinates');
  assert.ok(custom.offsets[customIndex(6)*3]>.75 && custom.offsets[customIndex(6)*3]<=.9,'Custom spacing scales repulsion');
  console.log('Influence: nine-second colour trail, smooth outward repulsion and return, fixed core/far grid, reset, boundaries, 30/60/120 FPS equivalence and 50/100/150/custom grid spacing passed.');
})().catch(e=>{console.error(e);process.exitCode=1;});
