const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const app=fs.readFileSync('app.js','utf8');
const planets=vm.runInNewContext(app.match(/const PLANETS = (\[[\s\S]*?\n\]);/)[1]);
const source=fs.readFileSync('planet-charts.js','utf8').replaceAll('export function','function');
const build=vm.runInNewContext(source+'\nbuildPlanetCharts;');
const html=build(planets);
assert.equal((html.match(/<svg /g)||[]).length,1);
assert.equal((html.match(/class="chart-planet"/g)||[]).length,8);
assert.equal((html.match(/<circle /g)||[]).length,40);
assert.equal((build(planets,'Earth').match(/class="chart-planet"/g)||[]).length,1);
assert.match(build(planets,'',2),/chart-planet is-selected/);
assert.match(build(planets,'',2),/<b>365\.256<\/b>/);
assert.doesNotMatch(build(planets,'Mars',2),/is-selected/);
assert.match(build(planets,'不存在'),/NO MATCHING PLANETS/);
assert.match(html,/60,182/);
assert.match(html,/0\.3871/);
assert.doesNotMatch(html,/NaN|Infinity|undefined/);
console.log('Unified chart: one SVG, eight paths, five metrics, selection and filtering passed.');
